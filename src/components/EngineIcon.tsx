const BRANDS: Partial<
  Record<EngineGlyph, (props: { size: number }) => ReactElement>
> = {
  google: GoogleMark,
  bing: BingMark,
  baidu: BaiduMark,
  duckduckgo: DuckDuckGoMark,
};

export function EngineIcon({
  engine,
  size = 16,
}: {
  engine: ResolvedEngine;
  size?: number;
}) {
  if (engine.kind === "builtin" && engine.glyph) {
    // A globe keeps the browser default from echoing the search field's own
    // magnifier when the two sit side by side.
    if (engine.glyph === "default")
      return <Globe size={size} strokeWidth={1.6} aria-hidden="true" />;
    const Brand = BRANDS[engine.glyph];
    if (Brand) return <Brand size={size} />;
  }
  return (
    <span
      className="engine-glyph"
      aria-hidden="true"
      style={{
        width: size,
        height: size,
        fontSize: Math.round(size * 0.74),
      }}
    >
      {(Array.from(engine.name)[0] ?? "?").toUpperCase()}
    </span>
  );
}
